import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();
const wrongServer = resolve(root, "server.ts");
const routesDirectory = resolve(root, "src/routes");
const routeTree = resolve(root, "src/routeTree.gen.ts");

const errors = [];

if (existsSync(wrongServer)) {
  const content = readFileSync(wrongServer, "utf8");
  if (content.includes("automatically generated by TanStack Router") || content.includes("./routes/__root")) {
    errors.push("server.ts foi gerado na raiz. O arquivo correto é src/routeTree.gen.ts.");
  } else {
    errors.push("server.ts não deve existir na raiz; o servidor oficial fica em src/server.ts.");
  }
}

if (!existsSync(routesDirectory)) errors.push("Diretório obrigatório src/routes não encontrado.");
if (!existsSync(routeTree)) errors.push("Árvore de rotas obrigatória src/routeTree.gen.ts não encontrada.");

if (errors.length) {
  console.error("\nEstrutura inválida do projeto:\n- " + errors.join("\n- "));
  process.exit(1);
}

console.log("Estrutura do projeto validada.");
